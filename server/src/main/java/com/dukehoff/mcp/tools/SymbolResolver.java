package com.dukehoff.mcp.tools;

import com.sun.source.tree.CompilationUnitTree;
import com.sun.source.tree.Tree;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.EnumSet;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.concurrent.atomic.AtomicReference;
import java.util.stream.Collectors;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.util.Types;
import org.netbeans.api.java.source.ClassIndex;
import org.netbeans.api.java.source.ClasspathInfo;
import org.netbeans.api.java.source.CompilationInfo;
import org.netbeans.api.java.source.ElementHandle;
import org.netbeans.api.java.source.JavaSource;
import org.netbeans.api.java.source.TreePathHandle;
import com.dukehoff.mcp.Offered;
import org.openide.filesystems.FileObject;

/**
 * Resolves a {@link SymbolSpec} to a declaration in the workspace sources.
 */
final class SymbolResolver {

    /**
     * A resolved symbol.
     *
     * @param handle handle usable by the refactoring API
     * @param signature canonical symbol string, in the same syntax agents use as input
     * @param kind element kind, e.g. METHOD
     * @param file source file declaring the symbol
     * @param simpleName simple name of the element, e.g. {@code save} or {@code Order}
     * @param topLevelType whether the element is a top-level type (declared directly in its file)
     */
    /**
     * @param generated a member an annotation processor generated (Lombok's getters, builders): it has no
     *        source, and NetBeans' refactorings compile without processors, so they cannot see it
     */
    record Resolved(TreePathHandle handle, String signature, ElementKind kind, FileObject file,
            String simpleName, boolean topLevelType, boolean generated) {

        /** The error for refactorings, which cannot change a member without source. */
        String generatedError() {
            return signature + " is generated by an annotation processor (e.g. Lombok) and has no source. "
                    + "Change what it is generated from instead: the field, or the annotation on the class.";
        }
    }

    /** Resolution failed in a way the agent can fix; the message says how. */
    static final class ResolutionException extends Exception {

        ResolutionException(String message) {
            super(message);
        }
    }

    private SymbolResolver() {
    }

    static Resolved resolve(SymbolSpec given, List<FileObject> sourceRoots) throws IOException, ResolutionException {
        // a simple or partly qualified type name (PictureEditController, command.PictureEditController):
        // agents often know no more, and looking up the package cost them a grep or find_symbol call
        SymbolSpec spec = findSourceFile(given.typeName(), sourceRoots) != null ? given
                : new SymbolSpec(qualify(given.typeName(), sourceRoots), given.member(), given.parameterTypes());
        FileObject file = findSourceFile(spec.typeName(), sourceRoots);
        if (file == null) {
            throw new ResolutionException("Cannot find the source of " + spec.typeName());
        }
        JavaSource js = JavaSource.forFileObject(file);
        if (js == null) {
            throw new ResolutionException("Cannot parse " + file.getPath());
        }
        AtomicReference<Resolved> result = new AtomicReference<>();
        AtomicReference<String> problem = new AtomicReference<>();
        js.runUserActionTask(cc -> {
            cc.toPhase(JavaSource.Phase.RESOLVED);
            TypeElement type = cc.getElements().getTypeElement(spec.typeName());
            if (type == null) {
                problem.set("Type " + spec.typeName() + " not found in " + file.getNameExt());
                return;
            }
            Element target = type;
            if (spec.member() != null) {
                List<Element> candidates = new ArrayList<>();
                List<Element> sameName = new ArrayList<>();
                for (Element e : type.getEnclosedElements()) {
                    if (!nameMatches(spec, e)) {
                        continue;
                    }
                    sameName.add(e);
                    if (spec.parameterTypes() == null || parametersMatch(spec, e, cc.getTypes())) {
                        candidates.add(e);
                    }
                }
                if (candidates.isEmpty()) {
                    problem.set(sameName.isEmpty()
                            ? "No member '" + spec.member() + "' in " + spec.typeName()
                            : "No overload of '" + spec.member() + "' with parameters " + spec.parameterTypes()
                            + ". Candidates: " + signatures(sameName, cc));
                    return;
                }
                if (candidates.size() > 1) {
                    problem.set("'" + spec.member() + "' is ambiguous, add parameter types. Candidates: "
                            + signatures(candidates, cc));
                    return;
                }
                target = candidates.get(0);
            }
            // members generated by an annotation processor (Lombok's getters, builders) sit in the tree
            // without a source position: a position-based handle resolves to the wrong element elsewhere,
            // so refer to them by signature. Implicit constructors work with the usual handle.
            Tree tree = cc.getTrees().getTree(target);
            boolean generated = target.getKind() != ElementKind.CONSTRUCTOR && (tree == null || span(cc, tree) == null);
            TreePathHandle handle = generated
                    ? TreePathHandle.from(ElementHandle.create(target), cc.getClasspathInfo())
                    : TreePathHandle.create(target, cc);
            result.set(new Resolved(handle, signature(target, cc), target.getKind(), file,
                    target.getSimpleName().toString(),
                    target instanceof TypeElement te && !te.getNestingKind().isNested(), generated));
        }, true);
        if (result.get() == null) {
            throw new ResolutionException(problem.get() != null ? problem.get() : "Cannot resolve " + spec);
        }
        return result.get();
    }

    /**
     * Finds the file declaring a top-level or nested type by trying
     * {@code a/b/C.java}, then treating trailing segments as nested classes.
     */
    /**
     * The qualified name of the one workspace type whose name is or ends with {@code typeName}.
     */
    static String qualify(String typeName, List<FileObject> sourceRoots) throws ResolutionException {
        String qualified = qualifyInSources(typeName, sourceRoots);
        if (qualified == null) {
            String simple = typeName.substring(typeName.lastIndexOf('.') + 1);
            throw new ResolutionException("No type " + typeName + " in the workspace sources (only outline and "
                    + "find_symbol cover library types). " + (Offered.has("find_symbol")
                    ? "Use find_symbol with a prefix or glob, e.g. \"" + simple.substring(0, Math.min(4, simple.length())) + "*\", to look it up."
                    : "Check the name, e.g. by searching the sources for the class declaration."));
        }
        return qualified;
    }

    /**
     * The qualified name of the one workspace type whose name is or ends with {@code typeName}, or null
     * when no workspace type matches.
     *
     * @throws ResolutionException several match
     */
    static String qualifyInSources(String typeName, List<FileObject> sourceRoots) throws ResolutionException {
        String simple = typeName.substring(typeName.lastIndexOf('.') + 1);
        Set<String> matches = new TreeSet<>();
        for (FileObject root : sourceRoots) {
            Set<ElementHandle<TypeElement>> types = ClasspathInfo.create(root).getClassIndex()
                    .getDeclaredTypes(simple, ClassIndex.NameKind.SIMPLE_NAME, EnumSet.of(ClassIndex.SearchScope.SOURCE));
            if (types == null) {
                continue;
            }
            for (ElementHandle<TypeElement> h : types) {
                String fqn = h.getQualifiedName().replace('$', '.');
                if (fqn.equals(typeName) || fqn.endsWith("." + typeName)) {
                    matches.add(fqn);
                }
            }
        }
        if (matches.isEmpty()) {
            return null;
        }
        if (matches.size() > 1) {
            throw new ResolutionException("'" + typeName + "' is ambiguous, write the type qualified. Candidates: "
                    + String.join(", ", matches));
        }
        return matches.iterator().next();
    }

    static FileObject findSourceFile(String typeName, List<FileObject> sourceRoots) {
        String[] segments = typeName.split("\\.");
        for (int i = segments.length; i >= 1; i--) {
            String path = String.join("/", Arrays.copyOfRange(segments, 0, i)) + ".java";
            for (FileObject root : sourceRoots) {
                FileObject fo = root.getFileObject(path);
                if (fo != null && fo.isData()) {
                    return fo;
                }
            }
        }
        return null;
    }

    private static boolean nameMatches(SymbolSpec spec, Element e) {
        if (spec.isConstructor()) {
            return e.getKind() == ElementKind.CONSTRUCTOR;
        }
        return switch (e.getKind()) {
            case METHOD, FIELD, ENUM_CONSTANT, RECORD_COMPONENT -> e.getSimpleName().contentEquals(spec.member());
            default -> false;
        };
    }

    private static boolean parametersMatch(SymbolSpec spec, Element e, Types types) {
        if (!(e instanceof ExecutableElement ee)) {
            return false;
        }
        List<? extends VariableElement> params = ee.getParameters();
        if (params.size() != spec.parameterTypes().size()) {
            return false;
        }
        for (int i = 0; i < params.size(); i++) {
            String erasure = types.erasure(params.get(i).asType()).toString();
            if (!SymbolSpec.parameterMatches(spec.parameterTypes().get(i), erasure)) {
                return false;
            }
        }
        return true;
    }

    private static String signatures(List<Element> elements, CompilationInfo info) {
        return elements.stream().map(e -> signature(e, info)).collect(Collectors.joining(", "));
    }

    /**
     * Line (1-based) where an element is declared in the compilation unit of
     * {@code info}, or 0 if it has no source position there.
     */
    static int line(CompilationInfo info, Element e) {
        Tree tree = info.getTrees().getTree(e);
        if (tree == null) {
            return 0;
        }
        int[] span = span(info, tree);
        return span == null ? 0 : (int) info.getCompilationUnit().getLineMap().getLineNumber(span[0]);
    }

    /**
     * Start and end offset of a tree in the compilation unit of {@code info},
     * or {@code null} if it has no source position.
     */
    // The module compiles against the JDK's javac API, which (up to JDK 24) has only the
    // (CompilationUnitTree, Tree) methods; NetBeans' newer nb-javac deprecates them in favor
    // of (Tree) variants but keeps them, delegating to the new ones.
    @SuppressWarnings("deprecation")
    static int[] span(CompilationInfo info, Tree tree) {
        CompilationUnitTree cu = info.getCompilationUnit();
        long start = info.getTrees().getSourcePositions().getStartPosition(cu, tree);
        long end = info.getTrees().getSourcePositions().getEndPosition(cu, tree);
        return start < 0 || end < start ? null : new int[]{(int) start, (int) end};
    }

    /** Canonical symbol string of an element, in the syntax {@link SymbolSpec} parses. */
    static String signature(Element e, CompilationInfo info) {
        if (e instanceof TypeElement te) {
            return te.getQualifiedName().toString();
        }
        String owner = ((TypeElement) e.getEnclosingElement()).getQualifiedName().toString();
        if (e instanceof ExecutableElement ee) {
            String name = ee.getKind() == ElementKind.CONSTRUCTOR ? SymbolSpec.CONSTRUCTOR : ee.getSimpleName().toString();
            String params = ee.getParameters().stream()
                    .map(p -> info.getTypes().erasure(p.asType()).toString())
                    .collect(Collectors.joining(","));
            return owner + "#" + name + "(" + params + ")";
        }
        return owner + "#" + e.getSimpleName();
    }
}
